"""Tests for the tracked Rust file-size guard."""

import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest

SCRIPT = Path(__file__).with_name("check-file-sizes.py")


class FileSizeGuardTest(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        subprocess.run(["git", "init", "-q", str(self.root)], check=True)
        (self.root / "scripts").mkdir()
        self.exceptions([])

    def exceptions(self, entries):
        (self.root / "scripts/file-size-exceptions.json").write_text(json.dumps(entries))

    def source(self, name, lines, first="line\n"):
        path = self.root / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(first + "line\n" * (lines - 1))
        subprocess.run(["git", "-C", str(self.root), "add", "--", name], check=True)

    def guard(self):
        return subprocess.run(
            [sys.executable, str(SCRIPT), "--root", str(self.root)],
            capture_output=True, text=True, check=False,
        )

    def test_size_budgets_and_test_exemptions(self):
        self.exceptions([{"path": "src/old.rs", "max_lines": 5001, "reason": "Old file."}])
        self.source("src/old.rs", 5002)
        self.source("src/new.rs", 5001)
        for path in ("tests/integration.rs", "src/tests.rs", "src/unit_tests.rs", "bench/spikes/demo.rs"):
            self.source(path, 6000)
        result = self.guard()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("src/old.rs: 5002 lines exceeds exception maximum 5001", result.stderr)
        self.assertIn("src/new.rs: 5001 lines exceeds limit 5000", result.stderr)
        self.assertNotIn("tests.rs", result.stderr)
        self.assertNotIn("integration.rs", result.stderr)
        self.assertNotIn("demo.rs", result.stderr)
        self.source("src/old.rs", 5001)
        self.source("src/new.rs", 5000)
        self.assertEqual(self.guard().returncode, 0)

    def test_stale_and_reducible_exceptions(self):
        self.exceptions([
            {"path": "src/small.rs", "max_lines": 5001, "reason": "Old file."},
            {"path": "src/missing.rs", "max_lines": 5001, "reason": "Old file."},
            {"path": "src/shrunk.rs", "max_lines": 5002, "reason": "Old file."},
        ])
        self.source("src/small.rs", 5000)
        self.source("src/shrunk.rs", 5001)
        result = self.guard()
        self.assertNotEqual(result.returncode, 0)
        self.assertIn("src/small.rs: exception is stale", result.stderr)
        self.assertIn("src/missing.rs: exception is stale", result.stderr)
        self.assertIn("lower max_lines from 5002 to 5001", result.stdout)

    def test_generated_file_and_untracked_source(self):
        self.source("src/generated.rs", 6000, "// @generated by a tool\n")
        (self.root / "src/untracked.rs").write_text("line\n" * 6000)
        result = self.guard()
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn("generated exemption: src/generated.rs", result.stdout)


if __name__ == "__main__":
    unittest.main()
